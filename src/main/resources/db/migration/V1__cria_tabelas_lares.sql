CREATE TABLE LARES_USUARIO (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100 CHAR) NOT NULL,
    EMAIL VARCHAR2(150 CHAR) NOT NULL,
    SENHA_HASH VARCHAR2(100 CHAR) NOT NULL,
    PAPEL VARCHAR2(10 CHAR) NOT NULL,
    DATA_CADASTRO TIMESTAMP NOT NULL,
    CONSTRAINT PK_LARES_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UQ_LARES_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_LARES_USUARIO_PAPEL CHECK (PAPEL IN ('CIDADAO', 'GESTOR'))
);

CREATE TABLE LARES_CATEGORIA (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CODIGO VARCHAR2(20 CHAR) NOT NULL,
    NOME VARCHAR2(60 CHAR) NOT NULL,
    DESCRICAO VARCHAR2(255 CHAR),
    PRAZO_PADRAO_DIAS NUMBER(10) NOT NULL,
    CONSTRAINT PK_LARES_CATEGORIA PRIMARY KEY (ID),
    CONSTRAINT UQ_LARES_CATEGORIA_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_LARES_CATEGORIA_PRAZO CHECK (PRAZO_PADRAO_DIAS > 0)
);

CREATE TABLE LARES_OCORRENCIA (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID NUMBER(19) NOT NULL,
    CATEGORIA_ID NUMBER(19),
    DESCRICAO VARCHAR2(500 CHAR) NOT NULL,
    BAIRRO VARCHAR2(80 CHAR) NOT NULL,
    LATITUDE NUMBER(9, 6),
    LONGITUDE NUMBER(9, 6),
    STATUS VARCHAR2(15 CHAR) NOT NULL,
    PRIORIDADE VARCHAR2(5 CHAR),
    PRAZO_ESTIMADO_DIAS NUMBER(10),
    RESUMO_IA VARCHAR2(1000 CHAR),
    MENSAGEM_CIDADAO VARCHAR2(1000 CHAR),
    DATA_ABERTURA TIMESTAMP NOT NULL,
    DATA_ATUALIZACAO TIMESTAMP NOT NULL,
    CONSTRAINT PK_LARES_OCORRENCIA PRIMARY KEY (ID),
    CONSTRAINT FK_LARES_OCOR_USUARIO FOREIGN KEY (USUARIO_ID)
        REFERENCES LARES_USUARIO (ID),
    CONSTRAINT FK_LARES_OCOR_CATEGORIA FOREIGN KEY (CATEGORIA_ID)
        REFERENCES LARES_CATEGORIA (ID),
    CONSTRAINT CK_LARES_OCOR_STATUS CHECK (
        STATUS IN ('RECEBIDA', 'TRIADA', 'EM_ANDAMENTO', 'RESOLVIDA')
    ),
    CONSTRAINT CK_LARES_OCOR_PRIORIDADE CHECK (
        PRIORIDADE IS NULL OR PRIORIDADE IN ('BAIXA', 'MEDIA', 'ALTA')
    ),
    CONSTRAINT CK_LARES_OCOR_PRAZO CHECK (
        PRAZO_ESTIMADO_DIAS IS NULL OR PRAZO_ESTIMADO_DIAS > 0
    )
);

CREATE TABLE LARES_HISTORICO_STATUS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    OCORRENCIA_ID NUMBER(19) NOT NULL,
    USUARIO_ID NUMBER(19),
    STATUS_ANTERIOR VARCHAR2(15 CHAR),
    STATUS_NOVO VARCHAR2(15 CHAR) NOT NULL,
    COMENTARIO VARCHAR2(255 CHAR),
    DATA_ALTERACAO TIMESTAMP NOT NULL,
    CONSTRAINT PK_LARES_HIST_STATUS PRIMARY KEY (ID),
    CONSTRAINT FK_LARES_HIST_OCOR FOREIGN KEY (OCORRENCIA_ID)
        REFERENCES LARES_OCORRENCIA (ID) ON DELETE CASCADE,
    CONSTRAINT FK_LARES_HIST_USUARIO FOREIGN KEY (USUARIO_ID)
        REFERENCES LARES_USUARIO (ID) ON DELETE SET NULL,
    CONSTRAINT CK_LARES_HIST_STATUS_ANT CHECK (
        STATUS_ANTERIOR IS NULL OR
        STATUS_ANTERIOR IN ('RECEBIDA', 'TRIADA', 'EM_ANDAMENTO', 'RESOLVIDA')
    ),
    CONSTRAINT CK_LARES_HIST_STATUS_NOVO CHECK (
        STATUS_NOVO IN ('RECEBIDA', 'TRIADA', 'EM_ANDAMENTO', 'RESOLVIDA')
    )
);

CREATE INDEX IX_LARES_OCOR_USUARIO ON LARES_OCORRENCIA (USUARIO_ID);
CREATE INDEX IX_LARES_OCOR_CATEGORIA ON LARES_OCORRENCIA (CATEGORIA_ID);
CREATE INDEX IX_LARES_OCOR_BAIRRO_STATUS ON LARES_OCORRENCIA (BAIRRO, STATUS);
CREATE INDEX IX_LARES_HIST_OCOR_DATA ON LARES_HISTORICO_STATUS (OCORRENCIA_ID, DATA_ALTERACAO);
